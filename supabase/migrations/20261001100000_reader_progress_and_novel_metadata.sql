alter table public.novels add column if not exists genres text[] not null default '{}';
alter table public.novels add column if not exists reading_status text not null default 'ongoing' check (reading_status in ('ongoing','completed'));

create table if not exists public.reading_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  novel_id bigint not null references public.novels(id) on delete cascade,
  chapter_number integer not null check (chapter_number > 0),
  scroll_position numeric not null default 0 check (scroll_position >= 0),
  updated_at timestamptz not null default now(),
  primary key (user_id, novel_id)
);
create index if not exists reading_progress_user_updated_idx on public.reading_progress (user_id, updated_at desc);
alter table public.reading_progress enable row level security;
revoke all on public.reading_progress from anon, authenticated;

create table if not exists public.global_replacement_rules (
  id bigint generated by default as identity primary key,
  book_id text not null,
  source_text text not null check (char_length(source_text) between 1 and 300),
  replacement_text text not null check (char_length(replacement_text) <= 300),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (book_id, source_text)
);
create index if not exists global_replacement_rules_book_idx on public.global_replacement_rules (book_id, created_at asc);
alter table public.global_replacement_rules enable row level security;
revoke all on public.global_replacement_rules from anon, authenticated;
