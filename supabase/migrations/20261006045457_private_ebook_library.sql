create table if not exists public.ebook_books (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  file_name text not null,
  file_sha256 text not null check (file_sha256 ~ '^[0-9a-f]{64}$'),
  original_file_path text not null,
  source_format text not null check (source_format in ('epub', 'txt', 'html')),
  source_language text not null default 'unknown' check (source_language in ('zh', 'vi', 'unknown')),
  title text not null,
  author text,
  description text,
  status text not null default 'ready' check (status in ('ready', 'failed')),
  chapter_count integer not null default 0 check (chapter_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (owner_id, file_sha256)
);

create index if not exists ebook_books_owner_created_idx
  on public.ebook_books (owner_id, created_at desc);

create table if not exists public.ebook_chapters (
  id bigint generated by default as identity primary key,
  ebook_id uuid not null references public.ebook_books(id) on delete cascade,
  chapter_number integer not null check (chapter_number > 0),
  title text not null,
  content_path text not null,
  content_index smallint not null check (content_index >= 0),
  translation_status text not null default 'pending'
    check (translation_status in ('not_needed', 'pending', 'processing', 'translated', 'failed', 'unsupported')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (ebook_id, chapter_number)
);

create index if not exists ebook_chapters_ebook_number_idx
  on public.ebook_chapters (ebook_id, chapter_number);

alter table public.ebook_books enable row level security;
alter table public.ebook_chapters enable row level security;

grant select, insert, update, delete on public.ebook_books to authenticated;
grant select, insert, update, delete on public.ebook_chapters to authenticated;
grant all on public.ebook_books, public.ebook_chapters to service_role;
grant usage, select on sequence public.ebook_chapters_id_seq to service_role;
revoke all on public.ebook_books, public.ebook_chapters from anon;

drop policy if exists "ebook owners manage their books" on public.ebook_books;
create policy "ebook owners manage their books"
  on public.ebook_books for all to authenticated
  using ((select auth.uid()) = owner_id)
  with check ((select auth.uid()) = owner_id);

drop policy if exists "ebook owners manage their chapters" on public.ebook_chapters;
create policy "ebook owners manage their chapters"
  on public.ebook_chapters for all to authenticated
  using (exists (
    select 1 from public.ebook_books as book
    where book.id = ebook_id and book.owner_id = (select auth.uid())
  ))
  with check (exists (
    select 1 from public.ebook_books as book
    where book.id = ebook_id and book.owner_id = (select auth.uid())
  ));
