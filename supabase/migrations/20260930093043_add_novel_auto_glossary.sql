create table public.novel_auto_glossary (
  id bigint generated by default as identity primary key,
  novel_id bigint not null references public.novels(id) on delete cascade,
  source_text text not null,
  replacement_text text,
  appearances integer not null default 0 check (appearances >= 0),
  status text not null default 'candidate' check (status in ('candidate', 'auto_confirmed')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (novel_id, source_text)
);

create index novel_auto_glossary_novel_status_idx
  on public.novel_auto_glossary (novel_id, status);

alter table public.novel_auto_glossary enable row level security;
revoke all on public.novel_auto_glossary from anon, authenticated;
