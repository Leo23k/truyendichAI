create table public.replacement_rules (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  book_id text not null check (char_length(book_id) between 1 and 200),
  source_text text not null check (char_length(source_text) between 1 and 300),
  replacement_text text not null check (char_length(replacement_text) <= 300),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, book_id, source_text)
);

create index replacement_rules_user_book_idx
  on public.replacement_rules (user_id, book_id, created_at asc);

alter table public.replacement_rules enable row level security;
revoke all on public.replacement_rules from anon, authenticated;
